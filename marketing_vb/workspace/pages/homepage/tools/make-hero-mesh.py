#!/usr/bin/env python3
"""Build hero-body-mesh.json (the WebGL hero body) from an OBJ file.

Usage:
    python3 tools/make-hero-mesh.py <model.obj> [group] > ../hero-body-mesh.json

Today the mesh is the MakeHuman base mesh, group "body" (CC0 1.0,
makehumancommunity/makehuman, makehuman/data/3dobjs/base.obj). To show a body generated by the
3DLOOK model instead, export it as OBJ (A-pose, Y up) and run the script without a group.
Output: positions quantized to int16 within the bounding box, triangle indices as uint16,
both base64; page-v2-3d-2026-10-22.html decodes them.
"""
import base64, json, struct, sys

def main(path, group=None):
    verts, faces, current = [], [], None
    for line in open(path, encoding="utf-8", errors="ignore"):
        if line.startswith("v "):
            verts.append(tuple(map(float, line.split()[1:4])))
        elif line.startswith("g "):
            current = line.split()[1]
        elif line.startswith("f ") and (group is None or current == group):
            idx = [int(p.split("/")[0]) - 1 for p in line.split()[1:]]
            faces += [(idx[0], idx[i], idx[i + 1]) for i in range(1, len(idx) - 1)]
    used = sorted({i for f in faces for i in f})
    if len(used) > 65535:
        sys.exit("too many vertices for uint16 indices: decimate the mesh first")
    remap = {old: new for new, old in enumerate(used)}
    pts = [verts[i] for i in used]
    mn = [min(p[k] for p in pts) for k in range(3)]
    mx = [max(p[k] for p in pts) for k in range(3)]
    q = lambda v, k: int(round((v - mn[k]) / (mx[k] - mn[k]) * 65535)) - 32768
    pos = b"".join(struct.pack("<3h", *(q(p[k], k) for k in range(3))) for p in pts)
    idx = b"".join(struct.pack("<3H", remap[a], remap[b], remap[c]) for a, b, c in faces)
    json.dump({"source": path, "min": mn, "max": mx, "count": len(pts),
               "pos": base64.b64encode(pos).decode(), "idx": base64.b64encode(idx).decode()},
              sys.stdout, separators=(",", ":"))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
