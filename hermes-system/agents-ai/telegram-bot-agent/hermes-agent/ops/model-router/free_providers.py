# A negative verdict EXPIRES. Per-minute quotas make false negatives easy to
# collect — a model that failed while five agent turns were fired back to back can
# be perfectly healthy tomorrow — and a permanent ok:False would bury it forever.
# A positive verdict does not expire: proven-once is a good enough reason to try
# first, and if it broke, today's check demotes it.
NEGATIVE_TTL_DAYS = int(os.environ.get("HERMES_VERIFY_NEGATIVE_TTL_DAYS", "3"))


def _fresh(rec, today=None):
    try:
        import datetime as _dt
        d = _dt.date.fromisoformat(rec.get("date", ""))
        now = _dt.date.fromisoformat(today) if today else _dt.date.today()
        return (now - d).days < NEGATIVE_TTL_DAYS
    except Exception:
        return False


def verify_rank(v, ref, today=None):
    """Sort key: proven refs first, never-tried (or stale-negative) next, known-broken
    last, structurally-impossible refs dead last.

    A STRUCTURAL failure is sticky for the TTL and a later success does not clear it.
    Groq's gpt-oss-120b earned that rule: its free tier caps at 8000 tokens/minute
    while one agent turn is ~38k, so it cannot work — yet it answered exactly once,
    which was enough for a single-shot check to crown it and write a broken coder
    into the config. One success cannot outvote physics."""
    rec = v.get(ref)
    if not rec:
        return 1                     # unknown — worth a try
    if rec.get("hard") and _fresh(rec, today):
        return 3
    if rec.get("ok"):
        return 0
    try:
        import datetime as _dt
        d = _dt.date.fromisoformat(rec.get("date", ""))
        now = _dt.date.fromisoformat(today) if today else _dt.date.today()
        if (now - d).days >= NEGATIVE_TTL_DAYS:
            return 1                 # stale failure — give it another chance
    except Exception:
        pass
    return 2


