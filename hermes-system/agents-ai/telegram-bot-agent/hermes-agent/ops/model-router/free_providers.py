# --- quality scoring over history -------------------------------------------
# One measurement is noise, not evidence. Today's numbers show why: the same
# openrouter/nemotron-3-ultra ranged 14.5 → 80.6 tok/s across ten probes (a 5.5x
# spread), while google/gemini-3.5-flash-lite held 357 → 459 across twelve (±7%).
# Ranking on a single sample means ranking on whose queue happened to be empty.
#
# So the score answers "how bad does it get", not "how good was it once":
#     score = p25(tok/s) × success_rate × (1 − min(CV, 0.5))
# p25 instead of the mean because an agent making dozens of turns lives in the bad
# tail; success_rate because a model that answers half the time is useless however
# fast (glm-5.2 completed the form in 1-2 of 4 attempts); and the CV penalty because
# 400±20 beats 500±300 for anything that has to finish a task.
CV_PENALTY_CAP = 0.5          # never discount by more than half
MIN_SUCCESS_RATE = float(os.environ.get("HERMES_MIN_SUCCESS_RATE", "0.6"))
NEW_MODEL_DISCOUNT = 0.7      # a single sample is worth less than a proven record
HYSTERESIS = float(os.environ.get("HERMES_HYSTERESIS", "1.3"))


def _p25(vals):
    """Pessimistic speed. Few samples → take the worst one seen; the point is to
    stop being seduced by a lucky run."""
    v = sorted(vals)
    if len(v) < 4:
        return v[0]
    import math
    return v[max(0, math.ceil(0.25 * len(v)) - 1)]


def model_stats(hist, ref):
    """{n, ok, success_rate, p25, median, cv, score} over the recorded window."""
    rows = hist.get(ref) or []
    if not rows:
        return None
    # Entries written before the pass/fail flag existed were successes by
    # construction — only wins were logged back then — so a missing key means ok.
    oks = [r for r in rows if r.get("ok", True)]
    tps = [r["tps"] for r in oks if r.get("tps")]
    n, ok = len(rows), len(oks)
    if not tps:
        return {"n": n, "ok": ok, "success_rate": ok / n, "p25": 0.0,
                "median": 0.0, "cv": 0.0, "score": 0.0}
    import statistics as _st
    med = _st.median(tps)
    cv = (_st.stdev(tps) / _st.mean(tps)) if len(tps) > 1 else 0.0
    sr = ok / n
    score = _p25(tps) * sr * (1 - min(cv, CV_PENALTY_CAP))
    return {"n": n, "ok": ok, "success_rate": sr, "p25": _p25(tps),
            "median": med, "cv": cv, "score": score}


def quality_score(hist, ref, today_tps=None):
    """Score used for ranking. Falls back to today's single measurement, discounted,
    so a model we have never seen can still win — but has to win clearly."""
    st = model_stats(hist, ref)
    if st and st["n"] >= 2:
        return st["score"], st
    if today_tps:
        return today_tps * NEW_MODEL_DISCOUNT, st
    return 0.0, st


def record_probe(hist, ref, pr):
    """Every probe goes into the record, PASS OR FAIL — success_rate cannot be
    computed from a log that only kept the wins (which is what it did before)."""
    hist.setdefault(ref, []).append({
        "date": time.strftime("%Y-%m-%d"),
        "ok": bool(pr.get("ok")),
        "ms": pr.get("ms"),
        "tps": pr.get("tps"),
        "err": (pr.get("error") or "")[:60],
    })


def load_history():
    try:
        return json.load(open(HISTORY))
    except Exception:
        return {}


def save_history(hist, keep=14):
    for ref in list(hist):
        hist[ref] = hist[ref][-keep:]
    json.dump(hist, open(HISTORY, "w"), indent=2)


def baseline_tps(hist, ref):
    """Best tokens/sec we have ever measured for this model — our stand-in for a
    'declared' speed when the provider publishes none. Today's number against this
    is what reveals a provider that is merely busy right now."""
    vals = [r.get("tps") for r in hist.get(ref, []) if r.get("tps")]
    return max(vals) if vals else None
