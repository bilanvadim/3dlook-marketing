def _params_from_id(mid):
    """Crude size signal: '...-550b-a55b' -> 550. Used only when nothing better."""
    m = re.findall(r'(\d+(?:\.\d+)?)b\b', mid.lower())
    return max((float(x) for x in m), default=0.0)


# Not coding models — they show up in the same free lists and would otherwise win
# on size alone. A TTS or image model cannot write an HTML form.
_NOT_CODERS = ("tts", "-audio", "audio-", "image", "-vision-only", "robotics",
               "content-safety", "embed", "-live", "guard", "rerank", "whisper",
               "moderation", "-ocr")


def _is_coder(mid):
    low = mid.lower()
    return not any(w in low for w in _NOT_CODERS)


def _match_live_id(display, live):
    """Repo display name -> real API id.

    The repo prints human names ('Gemini 3 Flash', 'Gemma 4 31B Instruct') while
    the API serves ids with suffixes and abbreviations ('gemini-3-flash-preview',
    'gemma-4-31b-it'). Try the obvious transforms, then a prefix match, and give up
    rather than guess a name that does not exist."""
    cand = display.strip().lower().replace(" ", "-")
    variants = [cand, cand + "-preview", cand + "-latest",
                cand.replace("-instruct", "-it"),
                cand.replace("-instruct", "-it") + "-preview"]
    for v in variants:
        if v in live:
            return v
    pref = [m for m in live if m.startswith(cand + "-")]
    return sorted(pref, key=len)[0] if pref else None


# A coding agent spends many requests on one task (read files, edit, re-read,
# verify), so a model with 20 requests/day is unusable no matter how strong it is.
# Anything at or above this floor counts as "workable limits".
MIN_RPD = 100


def rpd(limits):
    """Requests/day stated in the repo's limits text, or None if not stated.

    Two spellings, because the source changed: the old repo wrote it out
    ('1,000 requests/day'), the new one abbreviates ('1,500 RPD', '2,000 RPD
    total; <=500 ...'). Deliberately NOT matching 'neurons/day' or other
    non-request budgets — those are a different currency and guessing a request
    count from them would silently gate the wrong providers out."""
    text = limits or ""
    m = re.search(r'([\d,]+)\s*requests?\s*/\s*day', text, re.I)
    if not m:
        m = re.search(r'([\d,]+)\s*RPD\b', text, re.I)
    return int(m.group(1).replace(",", "")) if m else None


def _rank(cands):
    """Strongest-first, WITHOUT mixing incompatible scales.

    OpenRouter's coding_index (~20-60) and the local strength table (~55-90) are
    different scales; ranking them together would hand the win to whichever model
    merely lacked a benchmark. So when any candidate carries a published
    coding_index, only those compete."""
    for c in cands:
        d = rpd(c.get("limits", ""))
        c["rpd"] = d
        # Unstated limits are treated as workable: most providers publish a
        # per-minute cap only, and refusing those would empty the pool.
        c["limits_ok"] = (d is None) or (d >= MIN_RPD)
    benched = [c for c in cands if c["score_src"] == "coding_index"]
    pool = benched if benched else cands
    # Workable limits first, then strength: the strongest model in the world is
    # useless to an agent that gets 20 requests a day.
    pool.sort(key=lambda r: (not r["limits_ok"], -r["score"], r["id"]))
    rest = sorted((c for c in cands if c not in pool),
                  key=lambda r: (not r["limits_ok"], -r["score"], r["id"]))
    return pool + rest


def list_free_models(prov, key, repo_entry, strength_table, default_strength):
    """Normalized free-model candidates for one provider.

    [{id, ctx, score, score_src, limits}] — ordered strongest-first.
    """
    pid, base = prov["id"], prov["base"]
    out = []

    if pid == "openrouter":
        # OpenRouter's own API is authoritative AND carries coding benchmarks.
        d = get_json(f"{base}/models", timeout=30)
        for m in d.get("data", []):
            mid = m.get("id", "")
            pricing = m.get("pricing") or {}
            is_free = mid.endswith(":free") or float(pricing.get("prompt", 1) or 0) == 0
            if not is_free or not _is_coder(mid):
                continue
            ci = (((m.get("benchmarks") or {}).get("artificial_analysis") or {})
                  .get("coding_index"))
            if ci is not None:
                score, src = float(ci), "coding_index"
            else:
                score, src = _heuristic(mid, strength_table, default_strength)
            out.append({"id": mid, "ctx": m.get("context_length") or 0,
                        "score": round(score, 1), "score_src": src,
                        "limits": repo_entry.get("limits", "")})

    elif pid == "google":
        # The repo's HTML table is the free-tier list; ids come from the live
        # OpenAI-compatible /models so we never invent a name.
        live = {m["id"].split("/")[-1] for m in
                get_json(f"{base}/models", key, timeout=30).get("data", [])}
        for disp, lim in repo_entry.get("table", []):
            mid = _match_live_id(disp, live)
            if not mid or not _is_coder(mid):
                continue
            score, src = _heuristic(mid, strength_table, default_strength)
            out.append({"id": mid, "ctx": 0, "score": round(score, 1),
                        "score_src": src, "limits": lim.replace("<br>", " / ")})

    elif pid == "cloudflare-workers-ai":
        # Workers AI has no OpenAI-style catalogue — GET /ai/v1/models is a 405.
        # Its own models/search does the job and filters to text generation, so the
        # image and speech models never enter the ranking in the first place.
        #
        # It does NOT say which models the account's plan includes: gpt-oss-120b
        # and kimi-k2.7-code look identical here, and only the second one 403s with
        # "not available on the Workers Free plan". Both are listed; the probe walk
        # sorts that out, and plan_locked() keeps the rejects from costing attempts.
        acc = base.rsplit("/ai/v1", 1)[0]
        d = get_json(f"{acc}/ai/models/search?task=Text%20Generation&per_page=100",
                     key, timeout=30)
        for m in d.get("result") or []:
            mid = m.get("name") or ""
            if not mid or not _is_coder(mid):
                continue
            ctx = 0
            for p in m.get("properties") or []:
                if p.get("property_id") == "context_window":
                    try:
                        ctx = int(p.get("value") or 0)
                    except (TypeError, ValueError):
                        ctx = 0
            score, src = _heuristic(mid, strength_table, default_strength)
            out.append({"id": mid, "ctx": ctx, "score": round(score, 1),
                        "score_src": src, "limits": repo_entry.get("limits", "")})

    else:
        # Generic path (NVIDIA NIM and friends): the repo lists no ids, so ask the
        # provider. Everything its free tier exposes is a candidate.
        try:
            d = get_json(f"{base}/models", key, timeout=30)
        except Exception:
            # Some endpoints only serve completions (Codestral 404s on /models).
            fixed = prov.get("models") or []
            if not fixed:
                raise
            d = {"data": [{"id": m} for m in fixed]}
        # OpenCode Zen is the exception: its /models mixes free and PAID models, and
        # the paid ones answer 401 "Insufficient balance" — three wasted probes every
        # morning. models.dev prices them, so keep only the $0 ones.
        free_only = None
        if pid == "opencode":
            try:
                from router_lib import load_catalog
                oc = load_catalog()["opencode"]["models"]
                free_only = {k for k, v in oc.items()
                             if (v.get("cost") or {}).get("input", 1) == 0}
            except Exception:
                free_only = None
        # Does this catalogue distinguish a free subset at all?
        marks_free = any(str(m.get("id", "")).endswith(":free") for m in d.get("data", []))
        for m in d.get("data", []):
            mid = m.get("id", "")
            if not mid or not _is_coder(mid):
                continue
            if free_only is not None and mid not in free_only:
                continue
            # Only filter by price on catalogues that MARK a free subset. Kilo lists
            # 344 models of which 13 carry ":free" — there the price is the signal.
            # Groq publishes list prices for models its FREE tier serves anyway
            # (gpt-oss-120b at 0.00000015/token), so filtering on price there threw
            # away its ten best candidates and kept three unpriced oddities.
            if marks_free:
                pricing = m.get("pricing") or {}
                try:
                    priced = float(pricing.get("prompt", 0) or 0) != 0
                except (TypeError, ValueError):
                    priced = False
                if priced and not mid.endswith(":free"):
                    continue
            score, src = _heuristic(mid, strength_table, default_strength)
            out.append({"id": mid, "ctx": 0, "score": round(score, 1),
                        "score_src": src, "limits": repo_entry.get("limits", "")})

    return _rank(out)


def _heuristic(mid, strength_table, default_strength):
    """(score, source) when no published coding benchmark exists."""
    # Lowercased: HuggingFace serves ids like "zai-org/GLM-5.2" and "moonshotai/
    # Kimi-K3", and the strength table is written in lower case — without this every
    # one of its 129 models fell through to default_strength and "strongest" became
    # whatever sorted first.
    base = mid.split("/")[-1].removesuffix(":free").lower()
    if base in strength_table:
        return float(strength_table[base]), "таблица сил"
    # family match: 'gemini-3.6-flash' -> try progressively shorter prefixes
    parts = base.split("-")
    for n in range(len(parts) - 1, 1, -1):
        if "-".join(parts[:n]) in strength_table:
            return float(strength_table["-".join(parts[:n])]), "таблица сил (семейство)"
    p = _params_from_id(base)
    if p:
        # 9B→~55, 30B→~62, 120B→~70, 550B→~80; log-ish, capped.
        return min(85.0, 45 + 13.0 * (p ** 0.25)), f"эвристика по размеру (~{p:g}B)"
    return float(default_strength), "дефолт"


