def fetch_readme(timeout=30):
    req = urllib.request.Request(README_URL)
    req.add_header("User-Agent", UA)
    with urllib.request.urlopen(req, timeout=timeout, context=CTX) as r:
        return r.read().decode("utf-8", "replace")


def _marked_block(md, name):
    """Text between <!-- BEGIN_name --> and <!-- END_name -->, or ''.

    The repo maintains these tables with a generator and the markers are what it
    writes them between, so they are the most stable handle in the file — far more
    stable than the emoji headings above them ('### ⚡ Permanent Free Tiers')."""
    start = md.find(f"<!-- BEGIN_{name} -->")
    if start < 0:
        return ""
    end = md.find(f"<!-- END_{name} -->", start)
    return md[start:end if end > 0 else len(md)]


def _table_rows(block):
    """Markdown table rows as lists of stripped cells, header/separator dropped."""
    rows = []
    for line in block.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if not cells or set("".join(cells)) <= set("-: "):
            continue                              # separator row
        rows.append(cells)
    return rows[1:] if rows else []               # drop the header row


def _first_href(cell):
    m = re.search(r'href="([^"]+)"', cell or "")
    return m.group(1) if m else ""


def parse_free_section(md):
    """Ordered [{name, url, limits, base, table, model_links}] — free tiers only.

    Source of truth is the PERMANENT_FREE table, in the repo's own order. The
    RENEWABLE table is deliberately ignored: those providers renew a credit
    balance rather than serving free models, which is the same reason the old
    source's trial-credits section never entered the rotation. OpenRouter now
    lives there.

    Two more tables are folded into each entry because the coder pick needs them:
      * QUICK_REF   → the provider's base URL (used only as a fallback; a base we
                      have hardcoded and probed beats one parsed out of a README).
      * BEST_MODELS → up to three model ids with their own rate limits. This is
                      what `limits` and `table` are built from, so the per-model
                      requests/day gate keeps working now that the provider-level
                      '**Limits:**' prose is gone.
    """
    rows = _table_rows(_marked_block(md, "PERMANENT_FREE"))
    if not rows:
        return []

    bases = {}
    for r in _table_rows(_marked_block(md, "QUICK_REF")):
        if len(r) >= 2:
            bases[r[0]] = r[1].strip().strip("`")

    # BEST_MODELS repeats the provider name only on its first row; the following
    # rows leave that cell empty and belong to the same provider.
    best, current = {}, None
    for r in _table_rows(_marked_block(md, "BEST_MODELS")):
        if len(r) < 5:
            continue
        name, _disp, mid, ctx, lim = r[0], r[1], r[2].strip().strip("`"), r[3], r[4]
        if name:
            current = name
        if not current or not mid:
            continue
        best.setdefault(current, []).append({"id": mid, "ctx": ctx, "limits": lim})

    out = []
    for r in rows:
        if len(r) < 2:
            continue
        name = r[0]
        models = best.get(name, [])
        # The provider-level limit is the strictest thing we know about it: take the
        # first model line that states a real number rather than "See provider".
        lim = next((m["limits"] for m in models if rpd(m["limits"])), "")
        out.append({"name": name, "url": _first_href(r[-1]),
                    "limits": lim,
                    "base": bases.get(name, ""),
                    "free_models": r[1],
                    # Same shape the Google branch of list_free_models expects:
                    # (id, per-model limits). Ids here are real API ids, not display
                    # names, so _match_live_id has an easier job than it used to.
                    "table": [(m["id"], m["limits"]) for m in models],
                    "model_links": []})
    return out


# ------------------------------------------------------------------------- secrets
def _env_files():
    return [SECRETS, ENVF]


def find_key(prov):
    """First value found for any of the provider's key aliases, secrets file first.
    Returns (key, source_path, var_name) or (None, None, None)."""
    for path in _env_files():
        try:
            lines = open(path).read().splitlines()
        except OSError:
            continue
        for var in prov["env"]:
            for line in lines:
                if line.startswith(var + "="):
                    val = line.split("=", 1)[1].strip().strip('"\'')
                    if val:
                        return val, path, var
    return None, None, None


def _env_lookup(names):
    """First non-empty value among *names* across the env files."""
    for path in _env_files():
        try:
            lines = open(path).read().splitlines()
        except OSError:
            continue
        for var in names or ():
            for line in lines:
                if line.startswith(var + "="):
                    val = line.split("=", 1)[1].strip().strip('"\'')
                    if val:
                        return val
    return None


def cloudflare_account_id(key, persist=True):
    """Account id for the Workers AI path: env first, then ask Cloudflare.

    Discovery keeps this from being a second thing Sergiy has to paste by hand —
    the same token that calls the model can list the account it belongs to. The
    answer is written back to the secrets file so tomorrow costs no extra call.

    `persist=False` for --dry-run: that mode promises to touch nothing, and every
    other write in this run is guarded, so appending to a 0600 secrets file the
    operator did not expect to be modified would be the one exception."""
    got = _env_lookup(["CLOUDFLARE_ACCOUNT_ID"])
    if got:
        return got
    d = get_json("https://api.cloudflare.com/client/v4/accounts", key, timeout=30)
    accounts = d.get("result") or []
    if not accounts:
        raise RuntimeError("токен не видит ни одного аккаунта Cloudflare")
    acc = accounts[0].get("id")
    if acc and len(accounts) == 1 and persist:
        try:
            with open(SECRETS, "a") as f:
                f.write(f"\n# Найден автоматически по токену — путь Workers AI\n"
                        f"CLOUDFLARE_ACCOUNT_ID={acc}\n")
        except OSError:
            pass
    return acc


def ensure_base(prov, key, persist=True):
    """Fill a templated base URL in place. No-op for ordinary providers.

    Returns the resolved base, or raises so the caller reports the provider as
    unusable instead of probing a URL with a literal '{account_id}' in it."""
    base = prov.get("base") or ""
    if "{account_id}" not in base:
        return base
    acc = cloudflare_account_id(key, persist=persist)
    if not acc:
        raise RuntimeError("не удалось определить CLOUDFLARE_ACCOUNT_ID")
    prov["base"] = base.replace("{account_id}", acc)
    # Remembered so the OpenCode config gets an explicit baseURL for this provider:
    # a templated base means models.dev cannot build the URL without an env var the
    # CLI may not have. See set_opencode_model.
    prov["_base_templated"] = True
    return prov["base"]


def _error_message(body):
    """The human-readable reason out of an error body, whatever shape it came in.

    OpenAI-style providers use {"error": {"message": ...}}. Cloudflare uses
    {"errors": [{"message": ...}], "success": false} — plural, and a LIST. Reading
    only the singular form dropped Cloudflare's text entirely and left a bare
    "HTTP 403", which is how its "not available on the Workers Free plan" refusals
    went unrecognised: the phrase the detector looks for was being thrown away
    before the detector ever saw it.
    """
    if not isinstance(body, dict):
        return ""
    err = body.get("error")
    if isinstance(err, dict) and err.get("message"):
        return str(err["message"])
    if isinstance(err, str) and err:
        return err
    errs = body.get("errors")
    if isinstance(errs, list):
        for e in errs:
            if isinstance(e, dict) and e.get("message"):
                return str(e["message"])
            if isinstance(e, str) and e:
                return e
    return str(body.get("message") or "")


# A model that the account's plan does not include answers instantly (~150 ms)
# and will answer the same way tomorrow. It must not consume one of the few
