def coding_probe(prov, key, model, timeout=None, max_tokens=None,
                 _retry_of_truncation=False):
    """Send THE SAME coding task to every candidate and time it.

    Returns {ok, ms, gen_tokens, visible_tokens, tps, chars, inputs, truncated,
    error}.

    Two traps this deliberately avoids, both of which would rank a good provider
    as "slow server":
      * throughput is computed from ALL generated tokens (`total - prompt`), not
        from `completion_tokens`. Reasoning models bill most of their generation to
        hidden thinking: gemini-3.6-flash reported 43 completion tokens for a
        1228-token turn, which reads as 6 tok/s when the truth is ~180.
      * max_tokens is generous (4000). At 1200 the same model spent the whole
        budget thinking and returned a form cut off mid-tag — an unusable sample.
    `ok` also checks the answer IS a form (>=8 inputs), so a model that fails fast
    cannot win a speed contest."""
    timeout = timeout or PROBE_TIMEOUT_S
    max_tokens = max_tokens or PROBE_MAX_TOKENS
    body = json.dumps({"model": model, "max_tokens": max_tokens,
                       "messages": [{"role": "user", "content": CODING_PROMPT}]}).encode()
    req = urllib.request.Request(prov["base"] + "/chat/completions", data=body)
    req.add_header("User-Agent", UA)
    req.add_header("Authorization", "Bearer " + key)
    req.add_header("Content-Type", "application/json")
    t0 = time.monotonic()
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=CTX) as r:
            d = json.loads(r.read())
    except urllib.error.HTTPError as e:
        detail = ""
        try:
            detail = _error_message(json.loads(e.read()))[:120]
        except Exception:
            pass
        # 413 = our max_tokens exceeds what this model accepts per request. That is
        # our setting's fault, not the model's, so try once at half budget before
        # writing off a candidate (this is how Groq's gpt-oss-120b was being lost).
        if (e.code in (400, 413) and max_tokens > 2000
                and ("max_tokens" in detail or e.code == 413)):
            return coding_probe(prov, key, model, timeout=timeout,
                                max_tokens=max_tokens // 2,
                                _retry_of_truncation=_retry_of_truncation)
        return {"ok": False, "ms": int((time.monotonic() - t0) * 1000),
                "error": f"HTTP {e.code} {detail}".strip()}
    except Exception as e:
        return {"ok": False, "ms": int((time.monotonic() - t0) * 1000),
                "error": str(e)[:80]}
    ms = int((time.monotonic() - t0) * 1000)
    if "error" in d:
        return {"ok": False, "ms": ms, "error": str(d["error"])[:80]}
    try:
        choice = d["choices"][0]
        text = (choice["message"].get("content") or "")
    except Exception:
        return {"ok": False, "ms": ms, "error": "нет choices"}
    usage = d.get("usage") or {}
    visible = (usage.get("completion_tokens") or usage.get("output_tokens") or 0)
    total = usage.get("total_tokens") or 0
    prompt = usage.get("prompt_tokens") or usage.get("input_tokens") or 0
    gen = max(total - prompt, visible)          # includes hidden reasoning tokens
    secs = max(ms / 1000.0, 0.001)
    inputs = text.lower().count("<input")
    truncated = choice.get("finish_reason") == "length"
    # Order matters: truncation is checked BEFORE counting fields. Heavy reasoning
    # models (glm-5.2, deepseek-v4-pro, nemotron-3-ultra) spend the whole budget
    # thinking and stop mid-form, and reporting that as "не форма (2 полей)" hides
    # the actual reason — it reads as "answered the wrong thing" when the truth is
    # "cannot finish this inside 4000 tokens", which is itself a fair reason to
    # reject a backup coder.
    if not text.strip():
        err = "пустой ответ"
    elif truncated:
        # Not "N из 10": the count is of <input> tags actually emitted, and a
        # verbose model writes more than ten before running out (one printed
        # "16 из 10"). Report what it managed, not a fraction of the ask.
        err = (f"не уложился в {max_tokens} токенов — reasoning съел бюджет "
               f"(успел {inputs} полей, ответ оборван)")
    elif inputs < 8:
        err = f"не форма ({inputs} полей)"
    else:
        err = ""
    # A truncated answer is our budget's fault as much as the model's: on HuggingFace
    # GLM-5.2 generates at 217 tok/s — three times its speed on NVIDIA — and still
    # ran out mid-form. Give exactly those candidates ONE retry at double budget, so
    # a fast reasoning model is measured instead of written off. Only truncation
    # qualifies; a wrong answer or an empty one is not a budget problem.
    if truncated and max_tokens < 20000 and not _retry_of_truncation:
        return coding_probe(prov, key, model, timeout=int(timeout * 1.5),
                            max_tokens=max_tokens * 2, _retry_of_truncation=True)
    return {"ok": not err, "ms": ms, "gen_tokens": gen, "visible_tokens": visible,
            "tps": round(gen / secs, 1) if gen else None,
            "chars": len(text), "inputs": inputs, "truncated": truncated,
            "error": err}


def declared_speed(prov, key, model):
    """Reference tokens/sec to compare the measurement against.

    OpenRouter publishes rolling 30-minute throughput/latency per endpoint — the
    only provider of the three that does. Returns {tps, latency_ms, source} or
    {} when nobody publishes anything (then refresh.py falls back to our own
    rolling baseline from coder-history.json)."""
    if prov["id"] != "openrouter":
        return {}
    slug = model.removesuffix(":free")
    try:
        d = get_json(f"{prov['base']}/models/{slug}/endpoints", key, timeout=25)
    except Exception:
        return {}
    eps = ((d.get("data") or {}).get("endpoints") or [])
    tps = [v for v in (_p50(e.get("throughput_last_30m")) for e in eps) if v]
    lat = [v for v in (_p50(e.get("latency_last_30m")) for e in eps) if v]
    if not tps:
        return {}
    # Median across endpoints, not the best one: OpenRouter picks the endpoint, so
    # the fastest provider on the list is not what we are promised. Taking the max
    # would make an ordinary run look "slower than declared" every morning.
    return {"tps": round(_median(tps), 1),
            "latency_ms": round(_median(lat), 1) if lat else None,
            "source": "OpenRouter throughput_last_30m (p50, медиана по endpoint-ам)"}


def _p50(val):
    """Pull a number out of OpenRouter's rolling stats.

    With a key these fields are PERCENTILE DICTS
    (`{"p50": 34, "p75": 48, "p90": 65, "p99": 139}`); without one they came back
    as null, which is how a naive `max()` over them shipped and then blew up with
    "'>' not supported between instances of 'dict' and 'dict'" the moment a real key
    was added. Accepts a plain number too, in case the shape changes back."""
    if isinstance(val, (int, float)):
        return float(val)
    if isinstance(val, dict):
        for k in ("p50", "median", "p75", "value"):
            v = val.get(k)
            if isinstance(v, (int, float)):
                return float(v)
        nums = [v for v in val.values() if isinstance(v, (int, float))]
        return float(min(nums)) if nums else None
    return None


def _median(nums):
    s = sorted(nums)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2


