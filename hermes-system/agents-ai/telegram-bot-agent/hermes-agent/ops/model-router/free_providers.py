def _subprocess_env():
    """os.environ plus every VAR=value in ai-models.env (existing vars win).

    Parsed with the same dumb rules the rest of this module uses — no export
    keywords, no interpolation — because that file is written by hand and by the
    router, never sourced by a shell."""
    env = dict(os.environ)
    try:
        for line in open(SECRETS, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            k, v = k.strip(), v.strip().strip('"\'')
            if k and v and k not in env:
                env[k] = v
    except OSError:
        pass
    return env


def verify_backup_agent(timeout=180, retries=1, pause_s=None):
    """Run the REAL CLI and demand a real answer.

    The API probe is not representative of an agent turn: it sends ~30 tokens, while
    OpenCode ships a ~38k-token system prompt. Groq's free tier caps at 8000 tokens
    PER MINUTE, so gpt-oss-120b sailed through the probe at 435 tok/s and then failed
    every actual request with "Request too large ... TPM Limit 8000". Only running the
    thing catches that class of limit, so the winner is confirmed before it is kept.

    Two requests at most, VERIFY_PAUSE_S apart. An EMPTY answer is what a swallowed
    429 looks like, and it is easy to cause ourselves — the coding probe just spent
    quota on this very model, and Google's free flash-lite allows 15 requests per
    MINUTE. Structural failures (TPM too large, bad key) are not retried at all.

    The 5s gap does not by itself clear a per-minute window; what keeps the pressure
    off is the small number of checks (VERIFY_TOP_N=2) plus skipping the check
    entirely when the winner is the coder already running and already proven.

    Returns {ok, detail}."""
    import subprocess, time as _t
    pause_s = VERIFY_PAUSE_S if pause_s is None else pause_s
    if not os.path.isdir(os.path.join(VERIFY_DIR, ".git")):
        return {"ok": None, "detail": f"{VERIFY_DIR} не git-репозиторий — проверка пропущена"}
    for attempt in range(retries + 1):
      if attempt:
          _t.sleep(pause_s)          # cross the provider's per-minute window
      try:
          # Through a SHELL on purpose. Executed directly as an argv list the CLI
          # prints its header and exits 0 with NO answer, while the identical
          # command via bash returns BACKUP-OK in ~2s (measured both ways). A shell
          # is also how Hermes actually launches it — its terminal tool — so this
          # mirrors reality instead of testing a path nobody uses.
          import shlex
          cmd = (f"{shlex.quote(OPENCODE_BIN)} run "
                 f"{shlex.quote('Reply with exactly: BACKUP-OK')}")
          # -c, not -lc: sourcing the login profile made this hang for the full
          # timeout on one run. A plain shell keeps the behaviour that works
          # without dragging in profile scripts.
          # Hand the subprocess everything in ai-models.env. models.dev builds some
          # providers' base URLs out of env vars (Cloudflare's is
          # .../accounts/${CLOUDFLARE_ACCOUNT_ID}/ai/v1), and a systemd --user unit
          # inherits none of them — so without this the verification of such a
          # provider fails for a reason that has nothing to do with the model.
          r = subprocess.run(["bash", "-c", cmd],
                             cwd=VERIFY_DIR, capture_output=True, text=True,
                             env=_subprocess_env(), timeout=timeout)
      except subprocess.TimeoutExpired:
          # Transient by nature (slow model, provider queue) — let the retry decide,
          # and never record it as a structural verdict.
          detail = f"не ответил за {timeout}с"
          if attempt >= retries:
              return {"ok": False, "detail": detail, "hard": False}
          continue
      except Exception as e:
          return {"ok": False, "detail": str(e)[:80]}
      # The CLI colourises its output; raw escapes would land in the Telegram report.
      out = re.sub(r"\x1b\[[0-9;]*m", "", (r.stdout or "") + (r.stderr or ""))
      if "BACKUP-OK" in out:
          return {"ok": True, "detail": "" if not attempt else f"со 2-й попытки"}
      # Surface the provider's own complaint — that is where TPM/quota errors live.
      err = next((ln.strip() for ln in out.splitlines()
                  if "rror" in ln or "imit" in ln), "")
      detail = (err or "пустой ответ")[:120]
      if any(w in detail.lower() for w in _HARD_FAIL):
          return {"ok": False, "detail": detail, "hard": True}
    return {"ok": False, "detail": detail + " (и со 2-й попытки)", "hard": False}


